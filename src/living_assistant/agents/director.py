class PersonalAssistantDirector:
    """
    Root product director above specialized domains.
    Classifies user intents, coordinates Directive B4 requirements generation and user approval,
    dispatches tasks to the Software Company or direct tool executors, and synthesizes multi-domain outputs.
    """

    def __init__(
        self,
        model_manager: Any = None,
        orchestrator: Any = None,
        model: Optional[str] = None,
        context_tokens: int = 4096,
        software_company: Any = None,
        approval_manager: Optional[ApprovalManager] = None,
        resource_manager: Any = None,
        event_bus: Optional[EventBus] = None,
        prompt_engineer: Any = None,
    ):
        self.mm = model_manager
        self.orchestrator = orchestrator
        self.model = model or getattr(orchestrator, "model", "default")
        self.context_tokens = context_tokens
        self.software_company = software_company
        self.approval_manager = approval_manager
        self.resources = resource_manager
        self.event_bus = event_bus
        from living_assistant.agents.software_company.prompt_engineer import PromptEngineerAgent
        self.prompt_engineer = prompt_engineer or PromptEngineerAgent()

    # -------------------------------------------------------------------------
    # Intent Classification & Routing (Interface Contract 2)
    # -------------------------------------------------------------------------

    def classify_intent(self, user_prompt: str, context: Optional[Dict[str, Any]] = None) -> str:
        """Classifies intent into one of the 7 canonical domains."""
        plan = self.route_request(user_prompt, context)
        return plan.intent

    def route_request(self, user_prompt: str, context: Optional[Dict[str, Any]] = None) -> ExecutionPlan:
        """
        Interface Contract 2 implementation.
        Analyzes user_prompt and returns an ExecutionPlan.
        """
        fast_plan = self._heuristic_route(user_prompt, context)
        if fast_plan is not None:
            logger.info("[Director] Fast heuristic routed to intent: %s", fast_plan.intent)
            self._publish("director.routed", intent=fast_plan.intent, fast_path=True)
            return fast_plan

        return self._llm_route(user_prompt, context)

    def _heuristic_route(self, prompt: str, context: Optional[Dict[str, Any]] = None) -> Optional[ExecutionPlan]:
        """Deterministic fast-path routing for clear, unambiguous queries."""
        p = prompt.strip().lower()

        # Handle empty prompt edge case
        if not p:
            return ExecutionPlan(
                intent="personal",
                confidence=1.0,
                primary_domain="personal",
                domains_involved=["personal"],
                synthesis_instructions="Ask user how you can help them today.",
                rationale="Empty prompt defaulted to conversational inquiry.",
            )

        # Check for mixed intents with conjunctions
        conjunctions = [
            " and also ", " then remind me ", " after that ",
            " and set a reminder ", " and commit ", " and save to my notes ",
        ]
        has_conjunction = any(c in p for c in conjunctions)

        is_coding = bool(re.search(
            r"\b(write|implement|refactor|fix|debug|create|build)\b.*?\b(function|class|api|endpoint|route|method|service|test|script|module|cart|feature|project|app|application)\b|"
            r"\b(git\s+(commit|push|pull|diff|status|checkout|branch))\b|"
            r"\b(run|execute)\s+(pytest|tests|the test suite)\b|"
            r"\b(onboard|scan)\s+(the\s+)?(codebase|repo|repository)\b",
            p,
        ))

        is_personal = bool(re.search(
            r"\b(remind me to|set a reminder|add a reminder|my todos|list todos|remind me)\b|"
            r"\b(create|add)\s+a\s+todo\s+(?!app|project|api|service|backend|repo|system\b)\b|"
            r"\b(what('s| is) on my (calendar|schedule)|schedule a meeting|add to calendar)\b|"
            r"\b(remember that|what do you know about me|recall)\b",
            p,
        ))

        is_technical = bool(re.search(
            r"\b(system status|cpu usage|ram usage|disk space|hardware health|system metrics)\b|"
            r"\b(check logs|inspect database|query db|database status)\b",
            p,
        ))

        is_research = bool(re.search(
            r"\b(search (the )?web for|web search|look up|research|who is|what is the latest)\b",
            p,
        ))

        is_media = bool(re.search(
            r"\b(download (video|audio)|play (music|song|sound)|transcribe audio)\b",
            p,
        ))

        is_computer = bool(re.search(
            r"\b(take a screenshot|capture screen|active window|click the|press key)\b",
            p,
        ))

        # Mixed domain query
        detected_domains = []
        if is_coding: detected_domains.append("coding")
        if is_personal: detected_domains.append("personal")
        if is_technical: detected_domains.append("technical")
        if is_research: detected_domains.append("research")
        if is_media: detected_domains.append("media")
        if is_computer: detected_domains.append("computer")

        if len(detected_domains) >= 2 or (has_conjunction and len(detected_domains) >= 1):
            goal = CompanyGoal(
                goal=prompt.strip(),
                project_path=(context or {}).get("project_path"),
                requirements=[prompt.strip()],
                priority="normal",
                auto_verify=True,
                requires_user_approval=True,
                spec_status="PENDING_SPEC",
            ) if "coding" in detected_domains else None

            direct_actions = []
            for d in detected_domains:
                if d != "coding":
                    direct_actions.append({"domain": d, "action": f"{d}_action", "prompt": prompt})

            return ExecutionPlan(
                intent="mixed",
                confidence=0.92,
                primary_domain=detected_domains[0],
                domains_involved=detected_domains,
                direct_actions=direct_actions,
                company_task=goal,
                synthesis_instructions="Present results from all executed domains coherently.",
                rationale="Multi-domain request combining separate capabilities.",
            )

        if is_coding:
            refined = self.prompt_engineer.rewrite_prompt(prompt, target_dir="workspace/todo_app")
            goal = CompanyGoal(
                goal=refined.refined_prompt,
                project_path=(context or {}).get("project_path") or "workspace/todo_app",
                requirements=refined.key_features,
                priority="normal",
                auto_verify=True,
                requires_user_approval=True,
                spec_status="PENDING_SPEC",
            )
            return ExecutionPlan(
                intent="coding",
                confidence=0.98,
                primary_domain="coding",
                domains_involved=["coding"],
                company_task=goal,
                synthesis_instructions="Present the software goal or written specification clearly to the user.",
                rationale="Matched coding/development intent; refined via PromptEngineerAgent.",
            )

        if is_personal:
            return ExecutionPlan(
                intent="personal",
                confidence=0.98,
                primary_domain="personal",
                domains_involved=["personal"],
                direct_actions=[{"domain": "personal", "action": "personal_tool", "prompt": prompt}],
                synthesis_instructions="Confirm the personal action, reminder, or calendar item warmly and concisely.",
                rationale="Matched unambiguous personal assistant intent.",
            )

        if is_technical:
            return ExecutionPlan(
                intent="technical",
                confidence=0.95,
                primary_domain="technical",
                domains_involved=["technical"],
                direct_actions=[{"domain": "technical", "action": "system_diagnostics", "prompt": prompt}],
                synthesis_instructions="Present system metrics and diagnostics clearly.",
                rationale="Matched system telemetry/diagnostic query.",
            )

        if is_research:
            return ExecutionPlan(
                intent="research",
                confidence=0.95,
                primary_domain="research",
                domains_involved=["research"],
                direct_actions=[{"domain": "research", "action": "web_research", "prompt": prompt}],
                synthesis_instructions="Synthesize research passages with source citations.",
                rationale="Matched web research request.",
            )

        if is_media:
            return ExecutionPlan(
                intent="media",
                confidence=0.95,
                primary_domain="media",
                domains_involved=["media"],
                direct_actions=[{"domain": "media", "action": "media_operation", "prompt": prompt}],
                synthesis_instructions="Confirm media download or playback status.",
                rationale="Matched media processing request.",
            )

        if is_computer:
            return ExecutionPlan(
                intent="computer",
                confidence=0.95,
                primary_domain="computer",
                domains_involved=["computer"],
                direct_actions=[{"domain": "computer", "action": "desktop_action", "prompt": prompt}],
                synthesis_instructions="Describe desktop state and interaction results.",
                rationale="Matched desktop UI interaction request.",
            )

        return None

    def _llm_route(self, prompt: str, context: Optional[Dict[str, Any]] = None) -> ExecutionPlan:
        """LLM-based semantic routing for complex or ambiguous prompts."""
        if not self.mm or not getattr(self.mm, "provider", None):
            return self._fallback_plan(prompt, "No model manager configured")

        context_str = json.dumps(context or {}, default=str)[:4000]
        messages = [
            {"role": "system", "content": DIRECTOR_ROUTING_PROMPT},
            {"role": "user", "content": f"User Request:\n{prompt}\n\nContext:\n{context_str}"},
        ]

        try:
            format_schema = ExecutionPlan.model_json_schema()
        except Exception:
            format_schema = "json"

        lease = getattr(self.mm, "lease", None)
        lease_ctx = lease(self.model) if callable(lease) else nullcontext()

        try:
            with lease_ctx:
                data = self.mm.provider.chat(
                    self.model,
                    messages,
                    options={"num_ctx": self.context_tokens},
                    format=format_schema,
                )
            content = data.get("message", {}).get("content", "")
            parsed = self._extract_json(content)
            plan = ExecutionPlan(**parsed)
            if plan.company_task:
                plan.company_task.requires_user_approval = True
            self._publish("director.routed", intent=plan.intent, fast_path=False)
            return plan
        except Exception as exc:
            logger.warning("[Director] LLM routing failed: %s; using conservative fallback.", exc)
            return self._fallback_plan(prompt, str(exc))

    def _extract_json(self, raw_content: str) -> dict:
        cleaned = raw_content.strip()
        if cleaned.startswith("```"):
            lines = cleaned.split("\n")
            if lines[0].startswith("```"):
                lines = lines[1:]
            if lines and lines[-1].startswith("```"):
                lines = lines[:-1]
            cleaned = "\n".join(lines).strip()
        return json.loads(cleaned)

    def _fallback_plan(self, prompt: str, error_msg: str) -> ExecutionPlan:
        return ExecutionPlan(
            intent="personal",
            confidence=0.5,
            primary_domain="personal",
            domains_involved=["personal"],
            direct_actions=[{"domain": "personal", "action": "orchestrator_chat", "prompt": prompt}],
            synthesis_instructions="Provide a helpful direct answer to the user.",
            rationale=f"Fallback plan generated due to routing failure: {error_msg}",
        )

    # -------------------------------------------------------------------------
    # Directive B4 Requirements Generation & Gating Step
    # -------------------------------------------------------------------------

    def generate_requirements_spec(self, company_task: CompanyGoal) -> FunctionalSpec:
        """
        Directive B4 Step 1: Product Manager profile generates a visible written FunctionalSpec.
        """
        if self.mm and getattr(self.mm, "provider", None):
            messages = [
                {"role": "system", "content": PRODUCT_MANAGER_SPEC_PROMPT},
                {"role": "user", "content": f"User Goal:\n{company_task.goal}\n\nRequirements:\n{json.dumps(company_task.requirements)}\n\nConstraints:\n{json.dumps(company_task.constraints)}"},
            ]
            try:
                format_schema = FunctionalSpec.model_json_schema()
            except Exception:
                format_schema = "json"

            lease = getattr(self.mm, "lease", None)
            lease_ctx = lease(self.model) if callable(lease) else nullcontext()

            try:
                with lease_ctx:
                    data = self.mm.provider.chat(
                        self.model,
                        messages,
                        options={"num_ctx": self.context_tokens},
                        format=format_schema,
                    )
                content = data.get("message", {}).get("content", "")
                parsed = self._extract_json(content)
                spec = FunctionalSpec(**parsed)
            except Exception as exc:
                logger.warning("[Director] Product Manager spec generation failed: %s; using deterministic spec.", exc)
                spec = self._build_deterministic_spec(company_task)
        else:
            spec = self._build_deterministic_spec(company_task)

        company_task.spec = spec
        company_task.spec_status = "AWAITING_USER_APPROVAL"
        self._publish("requirements.spec_created", spec_id=spec.spec_id, title=spec.title)
        return spec

    def _build_deterministic_spec(self, company_task: CompanyGoal) -> FunctionalSpec:
        return FunctionalSpec(
            title=f"Specification for: {company_task.goal[:40]}",
            user_story=f"As a user, I want {company_task.goal}, so that the capability is available.",
            acceptance_criteria=company_task.requirements or [
                f"Implement core logic for {company_task.goal}",
                "Automated tests pass with exit code 0",
                "No regressions in pre-existing functionality",
            ],
            out_of_scope=["Unrelated codebase refactorings", "Destructive git operations"],
            non_functional_requirements=["Code passes automated tests", "No path traversal outside workspace"],
            target_files=list(company_task.context.get("target_files", [])),
        )

    def request_spec_approval(self, company_task: CompanyGoal) -> str:
        """
        Directive B4 Step 2: Register specification with ApprovalManager.
        """
        if not company_task.spec:
            self.generate_requirements_spec(company_task)

        spec = company_task.spec
        spec_summary = (
            f"Title: {spec.title}\n"
            f"User Story: {spec.user_story}\n"
            f"Acceptance Criteria:\n" + "\n".join(f"- {c}" for c in spec.acceptance_criteria)
        )

        if self.approval_manager is not None:
            if hasattr(self.approval_manager, "store") and self.approval_manager.store is not None:
                appr = self.approval_manager.store.create(
                    action=f"approve_spec::{spec.spec_id}",
                    reason=spec_summary,
                    kind="requirements_spec",
                )
                company_task.approval_id = appr["id"]
                return appr["id"]
            elif hasattr(self.approval_manager, "request"):
                appr = self.approval_manager.request(
                    action=f"approve_spec::{spec.spec_id}",
                    reason=spec_summary,
                    kind="requirements_spec",
                )
                company_task.approval_id = appr.get("approval_id", f"appr-{uuid.uuid4().hex[:8]}")
                return company_task.approval_id

        appr_id = f"appr-{uuid.uuid4().hex[:8]}"
        company_task.approval_id = appr_id
        return appr_id

    # -------------------------------------------------------------------------
    # Execution & Dispatch Coordination
    # -------------------------------------------------------------------------

    def execute(
        self,
        user_prompt: str,
        context: Optional[Dict[str, Any]] = None,
        session_id: Optional[str] = None,
        auto_approve_spec: bool = False,
    ) -> DirectorResponse:
        """
        End-to-end execution:
        1. Routes request to ExecutionPlan.
        2. Executes direct actions.
        3. Enforces Directive B4: Generates FunctionalSpec via PM profile.
           - If auto_approve_spec is False and approval is required, pauses and presents written spec.
           - If approved, hands over to Manager / Tech Lead workflow.
        4. Synthesizes multi-domain response.
        """
        start_time = time.perf_counter()
        plan = self.route_request(user_prompt, context)
        domain_results: Dict[str, Any] = {}
        requires_user_action = False
        pending_approval = None

        # 1. Execute direct actions
        if plan.direct_actions:
            direct_res = self._execute_direct_actions(plan.direct_actions, user_prompt, context, session_id)
            domain_results["direct_actions"] = direct_res

        # 2. Handle Software Company Task & Directive B4
        if plan.company_task:
            ct = plan.company_task
            if not ct.spec:
                self.generate_requirements_spec(ct)

            if ct.requires_user_approval and not ct.spec.approved and not auto_approve_spec:
                appr_id = self.request_spec_approval(ct)
                requires_user_action = True
                pending_approval = {
                    "approval_id": appr_id,
                    "kind": "requirements_spec",
                    "spec": ct.spec.model_dump(),
                }
                domain_results["company_task"] = {
                    "status": "AWAITING_USER_APPROVAL",
                    "spec": ct.spec.model_dump(),
                    "approval_id": appr_id,
                    "message": "Written specification created. User approval required before Manager decomposes tasks.",
                }
            else:
                ct.spec.approved = True
                ct.spec.approved_by = "user" if not auto_approve_spec else "auto_test"
                ct.spec.approved_at = time.time()
                ct.spec_status = "APPROVED"

                if self.software_company is not None:
                    if hasattr(self.software_company, "run_workflow"):
                        company_res = self.software_company.run_workflow(
                            goal=ct.goal,
                            context=ct.context,
                        )
                        domain_results["company_task"] = company_res.model_dump() if hasattr(company_res, "model_dump") else company_res
                    elif hasattr(self.software_company, "run"):
                        company_res = self.software_company.run(ct, session_id=session_id)
                        domain_results["company_task"] = company_res
                    else:
                        domain_results["company_task"] = {"status": "COMPLETED", "output": "Executed"}
                elif self.orchestrator is not None and hasattr(self.orchestrator, "run"):
                    company_res = self.orchestrator.run(user_prompt, context=str(context or ""), session_id=session_id)
                    domain_results["company_task"] = {"status": "COMPLETED", "output": company_res}

        # 3. Conversational fallback if no direct actions or company task
        if not plan.direct_actions and not plan.company_task:
            if self.orchestrator is not None and hasattr(self.orchestrator, "run"):
                chat_res = self.orchestrator.run(user_prompt, context=str(context or ""), session_id=session_id)
                domain_results["chat"] = chat_res
            else:
                domain_results["chat"] = f"Processed request: {user_prompt}"

        # 4. Synthesize multi-domain response
        final_answer = self.synthesize_response(
            plan=plan,
            action_results=domain_results.get("direct_actions", []),
            company_result=domain_results.get("company_task"),
        )

        elapsed = round(time.perf_counter() - start_time, 3)
        return DirectorResponse(
            answer=final_answer,
            plan=plan,
            domain_results=domain_results,
            execution_time_seconds=elapsed,
            session_id=session_id,
            requires_user_action=requires_user_action,
            pending_approval=pending_approval,
        )

    def _execute_direct_actions(
        self,
        actions: List[Dict[str, Any]],
        user_prompt: str,
        context: Optional[Dict[str, Any]],
        session_id: Optional[str],
    ) -> List[Dict[str, Any]]:
        results = []
        for action in actions:
            action_prompt = action.get("prompt") or user_prompt
            try:
                if self.orchestrator is not None and hasattr(self.orchestrator, "run"):
                    res = self.orchestrator.run(action_prompt, context=str(context or ""), session_id=session_id)
                else:
                    res = f"Direct action '{action.get('action')}' executed successfully."
                results.append({"action": action, "status": "success", "result": res})
            except Exception as e:
                results.append({"action": action, "status": "error", "error": str(e)})
        return results

    # -------------------------------------------------------------------------
    # Dual-Mode Response Synthesis
    # -------------------------------------------------------------------------

    def synthesize_response(
        self,
        plan: ExecutionPlan,
        action_results: List[Dict[str, Any]],
        company_result: Optional[Dict[str, Any]] = None,
    ) -> str:
        """
        Synthesizes multi-domain outputs into one coherent, human-facing response.
        Dual-mode synthesis: tries LLM synthesis if available, falls back to deterministic Markdown.
        """
        domain_results: Dict[str, Any] = {}
        if action_results:
            domain_results["direct_actions"] = action_results
        if company_result:
            domain_results["company_task"] = company_result

        if not domain_results:
            return "Your request has been processed successfully."

        if self.mm and getattr(self.mm, "provider", None):
            try:
                return self._llm_synthesize(plan, domain_results)
            except Exception as exc:
                logger.warning("[Director] LLM synthesis failed: %s; falling back to deterministic synthesis.", exc)

        return self._deterministic_synthesize(plan, domain_results)

    def synthesize(self, user_prompt: str, plan: ExecutionPlan, domain_results: Dict[str, Any]) -> str:
        """Convenience method matching alternate signature."""
        return self.synthesize_response(
            plan=plan,
            action_results=domain_results.get("direct_actions", []),
            company_result=domain_results.get("company_task"),
        )

    def _llm_synthesize(self, plan: ExecutionPlan, domain_results: Dict[str, Any]) -> str:
        summary_payload = {
            "intent": plan.intent,
            "synthesis_instructions": plan.synthesis_instructions,
            "domain_results": domain_results,
        }
        messages = [
            {"role": "system", "content": DIRECTOR_SYNTHESIS_PROMPT},
            {"role": "user", "content": f"Results to synthesize:\n{json.dumps(summary_payload, default=str)[:8000]}"},
        ]

        lease = getattr(self.mm, "lease", None)
        lease_ctx = lease(self.model) if callable(lease) else nullcontext()

        with lease_ctx:
            data = self.mm.provider.chat(
                self.model,
                messages,
                options={"num_ctx": self.context_tokens},
            )
        answer = data.get("message", {}).get("content", "").strip()
        if not answer:
            raise ValueError("Synthesizer model returned empty response")
        return answer

    def _deterministic_synthesize(self, plan: ExecutionPlan, domain_results: Dict[str, Any]) -> str:
        """
        Deterministic, zero-failure Markdown synthesis.
        Guarantees that no response is lost if the model fails.
        """
        lines = []

        # 1. Direct Actions Section
        if "direct_actions" in domain_results:
            lines.append("### Assistant Actions")
            for item in domain_results["direct_actions"]:
                status = "✓" if item.get("status") == "success" else "✗"
                res_preview = str(item.get("result") or item.get("error") or "")[:200]
                lines.append(f"- {status} {res_preview}")
            lines.append("")

        # 2. Software Company Section (including Directive B4 Spec)
        if "company_task" in domain_results:
            ct = domain_results["company_task"]
            lines.append("### Software Engineering")
            if isinstance(ct, dict):
                status = ct.get("status", "COMPLETED")
                lines.append(f"**Status**: {status}")
                if status == "AWAITING_USER_APPROVAL" and "spec" in ct:
                    spec = ct["spec"]
                    lines.append(f"**Written Specification**: {spec.get('title')}")
                    lines.append(f"_{spec.get('user_story')}_")
                    lines.append("\n**Acceptance Criteria**:")
                    for crit in spec.get("acceptance_criteria", []):
                        lines.append(f"- [ ] {crit}")
                    lines.append(f"\n_Please approve specification `{ct.get('approval_id')}` to begin development._")
                elif "output" in ct:
                    lines.append(f"\n{ct['output']}")
                if "files_modified" in ct:
                    lines.append(f"**Files Modified**: {', '.join(ct['files_modified'])}")
                if "final_qa_report" in ct and ct["final_qa_report"]:
                    qa = ct["final_qa_report"]
                    lines.append(f"QA Verification: {qa.get('status', 'N/A')} ({qa.get('passed', 0)} passed, {qa.get('failed', 0)} failed)")
            else:
                lines.append(str(ct))
            lines.append("")

        # 3. Fallback / Chat Section
        if "chat" in domain_results:
            lines.append(str(domain_results["chat"]))

        return "\n".join(lines).strip() or "Request processed."

    def _publish(self, event_type: str, **data) -> None:
        if self.event_bus is not None:
            try:
                self.event_bus.publish(event_type, **data)
            except Exception:
                pass
