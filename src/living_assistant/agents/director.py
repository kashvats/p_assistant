class FunctionalSpec(BaseModel):
    """
    Directive B4: Visible written specification generated by Product Manager profile.
    Must be approved by user before Manager / Tech Lead decomposes tasks.
    """
    model_config = ConfigDict(extra="ignore")

    spec_id: str = Field(default_factory=lambda: f"SPEC-{uuid.uuid4().hex[:8].upper()}")
    title: str = Field(description="Clear title of the requested feature or change")
    user_story: str = Field(description="User story: As a [role], I want [action], so that [outcome]")
    acceptance_criteria: List[str] = Field(description="Concrete testable acceptance criteria")
    out_of_scope: List[str] = Field(default_factory=list, description="Explicit boundaries and non-goals")
    non_functional_requirements: List[str] = Field(default_factory=list, description="Performance, security, accessibility requirements")
    target_files: List[str] = Field(default_factory=list, description="Expected files or modules impacted")
    created_at: float = Field(default_factory=time.time)
    approved: bool = Field(default=False, description="Whether the user has approved this written spec")
    approved_by: Optional[str] = Field(default=None, description="Identifier of approver (e.g., 'user', 'auto')")
    approved_at: Optional[float] = Field(default=None)


class CompanyGoal(BaseModel):
    """
    Software company task goal passed to the SoftwareCompanyWorkflow.
    Implements Directive B4 Requirements step gating.
    """
    model_config = ConfigDict(extra="ignore")

    goal: str = Field(description="High-level engineering objective")
    project_path: Optional[str] = Field(default=None, description="Path to target project/repository")
    requirements: List[str] = Field(default_factory=list, description="Decomposed functional/technical requirements")
    constraints: List[str] = Field(default_factory=list, description="Architectural and security constraints")
    priority: str = Field(default="normal", description="'low' | 'normal' | 'high' | 'critical'")
    context: Dict[str, Any] = Field(default_factory=dict, description="Codebase AST, dependencies, or system graph context")
    auto_verify: bool = Field(default=True, description="Whether independent QA and Verifier gating is mandatory")

    # Directive B4 Specification & Approval State
    requires_user_approval: bool = Field(default=True, description="Mandatory user approval gate for written spec")
    spec: Optional[FunctionalSpec] = Field(default=None, description="Visible written spec generated by Product Manager")
    spec_status: str = Field(
        default="PENDING_SPEC",
        description="'PENDING_SPEC' | 'AWAITING_USER_APPROVAL' | 'APPROVED' | 'REJECTED'",
    )
    approval_id: Optional[str] = Field(default=None, description="Tracking ID in ApprovalStore")


class ExecutionPlan(BaseModel):
    """Interface Contract 2 output schema for request routing."""
    model_config = ConfigDict(extra="ignore")

    intent: str = Field(description="Classified intent: 'personal' | 'technical' | 'coding' | 'research' | 'media' | 'computer' | 'mixed'")
    confidence: float = Field(default=1.0, ge=0.0, le=1.0, description="Confidence in classification (0.0 to 1.0)")
    primary_domain: str = Field(default="personal", description="Primary domain responsible for execution")
    domains_involved: List[str] = Field(default_factory=list, description="All domains involved in fulfilling request")
    direct_actions: List[Dict[str, Any]] = Field(default_factory=list, description="Immediate actions for personal/desktop/tools")
    company_task: Optional[CompanyGoal] = Field(default=None, description="Software company goal if coding/engineering is needed")
    synthesis_instructions: str = Field(default="", description="Guidance on how to combine multi-domain outputs for user")
    rationale: str = Field(default="", description="Reasoning behind routing decision")
    directive_b4_active: bool = Field(default=True, description="Indicates Directive B4 requirements flow is enforced")


class DirectorResponse(BaseModel):
    """End-to-end execution result returned by the Director."""
    model_config = ConfigDict(extra="ignore")

    answer: str
    plan: ExecutionPlan
    domain_results: Dict[str, Any] = Field(default_factory=dict)
    execution_time_seconds: float = 0.0
    session_id: Optional[str] = None
    requires_user_action: bool = False
    pending_approval: Optional[Dict[str, Any]] = None


